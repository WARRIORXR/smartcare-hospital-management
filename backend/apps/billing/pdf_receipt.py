"""
apps/billing/pdf_receipt.py
===========================
Generates clean formatted PDF hospital receipts using ReportLab.
"""

import io
from django.http import HttpResponse
from django.utils import timezone
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle


def build_invoice_pdf_response(invoice):
    """Build downloadable PDF receipt HttpResponse for a given Invoice instance."""
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=A4, topMargin=36, bottomMargin=36)
    styles = getSampleStyleSheet()
    elements = []

    elements.append(Paragraph("SmartCare Hospital — Official Billing Receipt", styles['Title']))
    elements.append(
        Paragraph(
            f"<b>Receipt No:</b> {invoice.invoice_number} &nbsp;|&nbsp; "
            f"<b>Status:</b> {invoice.status.upper()} &nbsp;|&nbsp; "
            f"<b>Date:</b> {invoice.created_at.strftime('%d %b %Y, %I:%M %p')}",
            styles['Normal'],
        )
    )
    elements.append(Spacer(1, 10))

    patient_name = invoice.patient.user.get_full_name() or invoice.patient.user.username
    patient_code = invoice.patient.patient_id or f"PAT-{invoice.patient.id:04d}"
    elements.append(
        Paragraph(
            f"<b>Patient:</b> {patient_name} ({patient_code}) &nbsp;|&nbsp; "
            f"<b>Phone:</b> {invoice.patient.user.phone or 'N/A'}",
            styles['Normal'],
        )
    )
    if invoice.token:
        elements.append(Paragraph(f"<b>Linked OPD Token:</b> {invoice.token.token_code}", styles['Normal']))
    if invoice.admission:
        elements.append(
            Paragraph(
                f"<b>Ward Stay:</b> {invoice.admission.bed.ward.name} — Bed {invoice.admission.bed.bed_number}",
                styles['Normal'],
            )
        )
    elements.append(Spacer(1, 16))

    item_rows = [['#', 'Service Description', 'Category', 'Qty', 'Unit Price (INR)', 'Amount (INR)']]
    for idx, item in enumerate(invoice.items.all(), start=1):
        item_rows.append([
            str(idx),
            item.description,
            item.get_category_display(),
            str(item.quantity),
            f"{item.unit_price:.2f}",
            f"{item.line_total:.2f}",
        ])

    item_rows.append(['', '', '', '', 'Subtotal', f"INR {invoice.subtotal:.2f}"])
    if invoice.tax_amount > 0:
        item_rows.append(['', '', '', '', 'Tax', f"INR {invoice.tax_amount:.2f}"])
    if invoice.discount_amount > 0:
        item_rows.append(['', '', '', '', 'Discount', f"- INR {invoice.discount_amount:.2f}"])
    item_rows.append(['', '', '', '', 'TOTAL DUE / PAID', f"INR {invoice.total_amount:.2f}"])

    table = Table(item_rows, colWidths=[28, 195, 95, 35, 80, 85])
    table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#0f172a')),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
        ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
        ('FONTNAME', (0, -1), (-1, -1), 'Helvetica-Bold'),
        ('BACKGROUND', (0, -1), (-1, -1), colors.HexColor('#eff6ff')),
        ('FONTSIZE', (0, 0), (-1, -1), 9),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#cbd5e1')),
        ('ALIGN', (3, 1), (-1, -1), 'RIGHT'),
        ('PADDING', (0, 0), (-1, -1), 6),
    ]))
    elements.append(table)
    elements.append(Spacer(1, 16))

    if invoice.status == 'paid':
        paid_str = invoice.paid_at.strftime('%d %b %Y, %I:%M %p') if invoice.paid_at else timezone.now().strftime('%d %b %Y')
        elements.append(
            Paragraph(
                f"<b>Payment Confirmed:</b> Paid via {(invoice.payment_method or 'Cash').upper()} on {paid_str}.",
                styles['Normal'],
            )
        )
    if invoice.notes:
        elements.append(Spacer(1, 6))
        elements.append(Paragraph(f"<b>Notes:</b> {invoice.notes}", styles['Normal']))

    elements.append(Spacer(1, 20))
    elements.append(
        Paragraph(
            "<i>Disclaimer: Generated by SmartCare HMS. For demonstration / educational billing preview only.</i>",
            styles['Italic'],
        )
    )

    doc.build(elements)
    buffer.seek(0)
    response = HttpResponse(buffer.getvalue(), content_type='application/pdf')
    response['Content-Disposition'] = f'attachment; filename="{invoice.invoice_number}_receipt.pdf"'
    return response
